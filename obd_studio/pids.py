GAUGE_PIDS = [0x0C, 0x0D, 0x05, 0x04]


def decode_value(pid, data):
    """Сирі байти → число або None, якщо даних замало."""
    p = PIDS.get(pid)
    if p is None or data is None:
        return None
    try:
        return float(p.decode(data))
    except (IndexError, TypeError):
        return None


def format_value(pid, value, with_unit=True):
    p = PIDS.get(pid)
    if p is None or value is None:
        return "—"
    text = f"{value:.{p.decimals}f}"
    return f"{text} {p.unit}".strip() if with_unit else text
